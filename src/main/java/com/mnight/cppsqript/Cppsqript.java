package com.mnight.cppsqript;

import com.mnight.cppsqript.api.CppSqriptAPI;
import com.mnight.cppsqript.api.RegisterCppSqriptCommandsEvent;
import com.mnight.cppsqript.parser.CppScriptLoader;
import com.mnight.cppsqript.parser.ScriptErrorTracker;
import com.mnight.cppsqript.recipe.BuiltInCommands;
import com.mnight.cppsqript.recipe.RecipeScriptManager;

import net.neoforged.bus.api.IEventBus;
import net.neoforged.bus.api.SubscribeEvent;
import net.neoforged.fml.common.Mod;
import net.neoforged.fml.event.lifecycle.FMLCommonSetupEvent;
import net.neoforged.neoforge.common.NeoForge;
import net.neoforged.neoforge.event.AddReloadListenerEvent;

import java.io.File;
import java.io.IOException;
import java.nio.file.Files;
import java.util.concurrent.atomic.AtomicBoolean;

// The value here should match an entry in the META-INF/neoforge.mods.toml file
@Mod(Cppsqript.MOD_ID)
public class Cppsqript {
    // Define mod id in a common place for everything to reference
    public static final String MOD_ID = "cppsqript";
        private static final AtomicBoolean IS_INITIALIZED = new AtomicBoolean(false);

    public Cppsqript(IEventBus modEventBus) {
        NeoForge.EVENT_BUS.register(this);
        modEventBus.addListener(this::onCommonSetup);
    }

    private void onCommonSetup(FMLCommonSetupEvent event) {
        // Guard against duplicate initialization calls
        if (!IS_INITIALIZED.compareAndSet(false, true)) {
            return;
        }

        // 1. Register built-in commands (remove, shapeless, shaped)
        BuiltInCommands.registerAll();

        // 2. Fire event to allow external addons to register custom C++ commands
        NeoForge.EVENT_BUS.post(new RegisterCppSqriptCommandsEvent());

        System.out.println("[CppSqript] Registered " + CppSqriptAPI.getHeaderSignatures().size() + " C++ script command(s).");
    }

    @SubscribeEvent
    public void onAddReloadListeners(AddReloadListenerEvent event) {
        loadCppScripts();
    }

    private void loadCppScripts() {
        RecipeScriptManager.clear();
        ScriptErrorTracker.clear();

        File scriptDir = new File("config/cppsqript");
        boolean isFirstRun = !scriptDir.exists();

        if (isFirstRun) {
            scriptDir.mkdirs();
        }

        // Always regenerate cppsqript.hpp to reflect newly installed addons
        generateDynamicHeader(scriptDir);

        // Create sample recipes.cpp only on the very first run
        if (isFirstRun) {
            createDefaultScript(scriptDir);
        }

        // Load all .cpp files in config/cppsqript and its subdirectories
        int count = CppScriptLoader.loadAllScripts(scriptDir.toPath());
        System.out.println("[CppSqript] Finished loading " + count + " C++ script file(s).");
    }

    private void generateDynamicHeader(File scriptDir) {
        File headerFile = new File(scriptDir, "cppsqript.hpp");
        StringBuilder sb = new StringBuilder();
        sb.append("// Auto-generated by CppSqript. Do not edit manually.\n");
        sb.append("#pragma once\n");
        sb.append("#include <initializer_list>\n");
        sb.append("#include <utility>\n\n");

        sb.append("namespace ServerEvents {\n");
        sb.append("    class Recipes {\n");
        sb.append("    public:\n");
        for (String sig : CppSqriptAPI.getHeaderSignatures()) {
            sb.append("        ").append(sig).append(" {}\n");
        }
        sb.append("    };\n");
        sb.append("}\n\n");

        sb.append("// Global command shortcuts\n");
        for (String sig : CppSqriptAPI.getHeaderSignatures()) {
            sb.append("inline ").append(sig).append(" {}\n");
        }

        try {
            Files.writeString(headerFile.toPath(), sb.toString());
        } catch (IOException e) {
            System.err.println("[CppSqript] Failed to generate cppsqript.hpp");
            e.printStackTrace();
        }
    }

    private void createDefaultScript(File scriptDir) {
        File defaultScript = new File(scriptDir, "recipes.cpp");
        try {
            String sampleCode = """
                    #include "cppsqript.hpp"

                    void register_recipes(ServerEvents::Recipes& event) {
                        // Variable examples
                        // auto planks = "#minecraft:planks";
                        // const char* stick = "minecraft:stick";

                        // 1. Remove an existing recipe
                        // event.remove("minecraft:diamond_sword");

                        // 2. Add a shapeless recipe
                        // event.shapeless("minecraft:diamond", 1, {"minecraft:dirt", "minecraft:dirt"});

                        // 3. Add a 3x3 shaped recipe
                        // event.shaped("minecraft:diamond_sword", 1, {
                        //     " P ",
                        //     " P ",
                        //     " S "
                        // }, {
                        //     {'P', planks},
                        //     {'S', stick}
                        // });
                    }
                    """;
            Files.writeString(defaultScript.toPath(), sampleCode);
            System.out.println("[CppSqript] Created default script: recipes.cpp");
        } catch (IOException e) {
            System.err.println("[CppSqript] Failed to create default recipes.cpp");
            e.printStackTrace();
        }
    }
}
